package com.github.deripas.tgbot.app.config;

import com.github.deripas.tgbot.app.users.User;
import com.github.deripas.tgbot.app.users.UserService;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.security.authentication.ott.InMemoryOneTimeTokenService;
import org.springframework.security.authentication.ott.OneTimeTokenAuthenticationProvider;
import org.springframework.security.authentication.ott.OneTimeTokenService;
import org.springframework.security.config.Customizer;
import org.springframework.security.config.annotation.web.builders.HttpSecurity;
import org.springframework.security.core.userdetails.UserDetails;
import org.springframework.security.core.userdetails.UserDetailsService;
import org.springframework.security.core.userdetails.UsernameNotFoundException;
import org.springframework.security.crypto.factory.PasswordEncoderFactories;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.security.web.SecurityFilterChain;
import org.springframework.security.web.authentication.SimpleUrlAuthenticationFailureHandler;

import java.util.Locale;
import java.util.Optional;

import static jakarta.servlet.http.HttpServletResponse.SC_NOT_FOUND;

/**
 * Web UI login, two ways:
 * <ul>
 *     <li>login and password in the form of {@link #LOGIN_PAGE};</li>
 *     <li>one-time link from the bot: {@code /login} in Telegram replies with {@code /login/ott?token=...},
 *     the page there submits the token. The link is only opened, not consumed, on GET, so the link preview
 *     of Telegram does not use it up. A user without a password is sent to {@link #ACCOUNT_PAGE} to choose
 *     the login and the password.</li>
 * </ul>
 * Either way the name of the authenticated principal is our user id.
 */
@Configuration(proxyBeanMethods = false)
class SecurityConfig {

    static final String LOGIN_PAGE = "/login";
    static final String LOGIN_LINK = "/login/ott";
    static final String ACCOUNT_PAGE = "/account";

    @Bean
    SecurityFilterChain securityFilterChain(HttpSecurity http, OneTimeTokenService tokens, UserService users) {
        return http
                .authorizeHttpRequests(requests -> requests
                        // the login page needs the styles before the login
                        .requestMatchers(LOGIN_PAGE, "/login/dev", "/actuator/health", "/css/**").permitAll()
                        .anyRequest().authenticated())
                .formLogin(form -> form.loginPage(LOGIN_PAGE))
                .oneTimeTokenLogin(ott -> ott
                        .loginPage(LOGIN_PAGE)
                        // the login page would be the processing URL too
                        .loginProcessingUrl(LOGIN_LINK)
                        .tokenService(tokens)
                        // the token holds the user id, not the login: the user may have no login yet
                        .authenticationProvider(new OneTimeTokenAuthenticationProvider(tokens, id -> parseId(id)
                                .flatMap(users::findById)
                                .map(SecurityConfig::details)
                                .orElseThrow(() -> new UsernameNotFoundException("Unknown user " + id))))
                        .successHandler((request, response, authentication) -> response.sendRedirect(
                                parseId(authentication.getName()).flatMap(users::findById).filter(User::hasPassword).isPresent()
                                        ? "/"
                                        : ACCOUNT_PAGE))
                        .failureHandler(new SimpleUrlAuthenticationFailureHandler(LOGIN_PAGE + "?expired"))
                        // tokens are only generated by the bot: requests to generate one in the Web UI are not served
                        .tokenGenerationSuccessHandler((request, response, token) -> response.sendError(SC_NOT_FOUND)))
                .logout(Customizer.withDefaults())
                .build();
    }

    /**
     * Valid for 5 minutes, used once; lost on restart.
     */
    @Bean
    OneTimeTokenService oneTimeTokenService() {
        return new InMemoryOneTimeTokenService();
    }

    @Bean
    PasswordEncoder passwordEncoder() {
        return PasswordEncoderFactories.createDelegatingPasswordEncoder();
    }

    /**
     * Users of the login form, found by the login.
     */
    @Bean
    UserDetailsService userDetailsService(UserService users) {
        return login -> users.findByLogin(login.toLowerCase(Locale.ROOT))
                .map(SecurityConfig::details)
                .orElseThrow(() -> new UsernameNotFoundException("Unknown login " + login));
    }

    /**
     * @return details named by the user id
     */
    private static UserDetails details(User user) {
        return org.springframework.security.core.userdetails.User.withUsername(String.valueOf(user.id()))
                // a user without a password logs in with a link only
                .password(user.hasPassword() ? user.passwordHash() : "")
                .roles(user.admin() ? new String[]{"USER", "ADMIN"} : new String[]{"USER"})
                .build();
    }

    private static Optional<Long> parseId(String username) {
        try {
            return Optional.of(Long.parseLong(username));
        } catch (NumberFormatException e) {
            return Optional.empty();
        }
    }
}
